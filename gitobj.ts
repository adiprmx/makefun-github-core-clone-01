export const PKT_LINE_MAX = 65520;
/** Max data bytes in one sideband packet: pkt-line cap minus the 4-byte length and 1 band byte. */
export const SIDEBAND_CHUNK = 65515;

export function encodePktLine(data: string | Uint8Array): Buffer {
  const body = typeof data === 'string' ? Buffer.from(data, 'utf8') : data;
  const header = Buffer.allocUnsafe(4);
  header.write((body.length + 4).toString(16).padStart(4, '0'), 0, 4, 'ascii');
  return Buffer.concat([header, body]);
}

export function pktLineFlush(): Buffer {
  return Buffer.from('0000', 'ascii');
}
export function pktLineDelim(): Buffer {
  return Buffer.from('0001', 'ascii');
}
export function pktLineResponseEnd(): Buffer {
  return Buffer.from('0002', 'ascii');
}

export function encodePktLines(items: ReadonlyArray<string | Uint8Array | 'flush' | 'delim' | 'response-end'>): Buffer {
  const parts: Buffer[] = [];
  for (const item of items) {
    if (item === 'flush') parts.push(pktLineFlush());
    else if (item === 'delim') parts.push(pktLineDelim());
    else if (item === 'response-end') parts.push(pktLineResponseEnd());
    else parts.push(encodePktLine(item));
  }
  return Buffer.concat(parts);
}

export type GitPacket =
  | { kind: 'flush' }
  | { kind: 'delim' }
  | { kind: 'response-end' }
  | { kind: 'data'; payload: Buffer };

/** Decode a complete buffer into packets. `allowTrailing` leaves raw (unframed) bytes unconsumed. */
export function decodePktLines(
  bytes: Uint8Array,
  options: { allowTrailing?: boolean } = {},
): { packets: GitPacket[]; rest: Buffer } {
  const buffer = Buffer.isBuffer(bytes) ? bytes : Buffer.from(bytes);
  const packets: GitPacket[] = [];
  let offset = 0;
  while (offset < buffer.length) {
    if (offset + 4 > buffer.length) throw new GitError('truncated pkt-line', 'pktline-truncated');
    const head = buffer.subarray(offset, offset + 4).toString('ascii');
    if (!/^[0-9a-fA-F]{4}$/.test(head)) {
      if (options.allowTrailing) break;
      throw new GitError(`invalid pkt-line length ${JSON.stringify(head)}`, 'pktline-header');
    }
    const length = Number.parseInt(head, 16);
    if (length === 0) {
      packets.push({ kind: 'flush' });
      offset += 4;
    } else if (length === 1) {
      packets.push({ kind: 'delim' });
      offset += 4;
    } else if (length === 2) {
      packets.push({ kind: 'response-end' });
      offset += 4;
    } else if (length === 3 || length > PKT_LINE_MAX) {
      throw new GitError(`invalid pkt-line length ${length}`, 'pktline-header');
    } else {
      if (offset + length > buffer.length) throw new GitError('truncated pkt-line', 'pktline-truncated');
      packets.push({ kind: 'data', payload: buffer.subarray(offset + 4, offset + length) });
      offset += length;
    }
  }
  return { packets, rest: buffer.subarray(offset) };
}

/** The decoded text of every data packet, control packets dropped. */
export function packetsToLines(packets: readonly GitPacket[]): string[] {
  const lines: string[] = [];
  for (const packet of packets) if (packet.kind === 'data') lines.push(packet.payload.toString('utf8'));
  return lines;
}

/** One sideband packet: band byte + data, pkt-line framed. Band 1 = pack data, 2 = progress, 3 = error. */
export function encodeSideband(band: 1 | 2 | 3, data: Uint8Array): Buffer {
  const body = Buffer.concat([Buffer.from([band]), Buffer.isBuffer(data) ? data : Buffer.from(data)]);
  return encodePktLine(body);
}

/** A buffer split into sideband band-1 packets of at most SIDEBAND_CHUNK bytes each. */
export function encodeSidebandData(data: Uint8Array): Buffer {
  const buffer = Buffer.isBuffer(data) ? data : Buffer.from(data);
  const parts: Buffer[] = [];
  for (let offset = 0; offset < buffer.length; offset += SIDEBAND_CHUNK) {
    parts.push(encodeSideband(1, buffer.subarray(offset, Math.min(buffer.length, offset + SIDEBAND_CHUNK))));
  }
  if (parts.length === 0) parts.push(encodeSideband(1, Buffer.alloc(0)));
  return Buffer.concat(parts);
}
